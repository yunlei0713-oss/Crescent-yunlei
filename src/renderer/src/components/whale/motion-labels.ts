export function whaleCategoryLabel(category: string, en: boolean): string {
  return categoryLabels[category]?.[en ? 1 : 0] ?? category
}

export function whaleMotionLabel(id: string, en: boolean): string {
  const name = id.split('/').at(-1) ?? id
  if (!en && motionLabels[name]) return motionLabels[name]
  const words = name.replaceAll('_', ' ')
  return words.charAt(0).toUpperCase() + words.slice(1)
}
